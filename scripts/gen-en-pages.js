// Generates pages/xen/* — the English copies of every page with static rendering. The middleware rewrites English
// visitors there; the browser URL never changes. Runs before dev/build; the folder is not committed.
const fs = require("fs");
const path = require("path");

const PAGES = path.join(__dirname, "..", "pages");
const OUT = path.join(PAGES, "xen");
const SKIP = new Set(["_app.tsx", "_document.tsx", "_error.tsx", "api", "xen"]);

fs.rmSync(OUT, { recursive: true, force: true });
let count = 0;

const walk = (dir) => {
  for (const name of fs.readdirSync(dir)) {
    const full = path.join(dir, name);
    const rel = path.relative(PAGES, full);
    if (SKIP.has(rel) || SKIP.has(name) && dir === PAGES) continue;
    if (fs.statSync(full).isDirectory()) {
      walk(full);
      continue;
    }
    if (!/\.tsx?$/.test(name)) continue;
    const src = fs.readFileSync(full, "utf8");
    // Server-rendered feeds (rss, sitemap) stay Russian only.
    if (/getServerSideProps/.test(src)) continue;
    const target = path.join(OUT, rel);
    fs.mkdirSync(path.dirname(target), { recursive: true });
    const importPath = path.relative(path.dirname(target), full).replace(/\\/g, "/").replace(/\.tsx?$/, "");
    const helpers = path.relative(path.dirname(target), path.join(__dirname, "..", "services", "i18nPages")).replace(/\\/g, "/");
    const hasProps = /export\s+(async\s+)?(function|const)\s+getStaticProps/.test(src);
    const lines = [
      "// Generated by scripts/gen-en-pages.js — English copy of the page. Do not edit.",
      `import Page from "${importPath}";`,
      hasProps ? `import { getStaticProps as sourceProps } from "${importPath}";` : "",
      `import { withEnglish, englishPaths } from "${helpers}";`,
      "",
      "export default Page;",
      `export const getStaticProps = withEnglish(${hasProps ? "sourceProps" : ""});`,
    ].filter((line, i) => line !== "" || i === 4);
    if (/getStaticPaths/.test(src)) lines.push("export const getStaticPaths = englishPaths;");
    fs.writeFileSync(target, lines.join("\n") + "\n");
    count++;
  }
};

walk(PAGES);
console.log(`[gen-en-pages] ${count} English page copies in pages/xen`);
